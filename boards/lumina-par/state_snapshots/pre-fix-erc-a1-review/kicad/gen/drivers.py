def _channel(sh: schlib.Sheet, n: int) -> None:
    """Build channel `n` (0..3). Refdes base = 300 + 20n, block = BLOCKS[n].

    Nets: `+12V` and `GND` are global (bare power symbols, no sheet pin).
    `DRV_ENn` / `SHUNTn` / `LEDn_A` are the hierarchical interface - the
    root places a local label of the SAME name on each, which is what turns
    them into the canonical `/DRV_ENn` / `/SHUNTn` / `/LEDn_A` of
    sheets.md s2 (a hierarchical label alone would yield `/drivers/NAME`).
    Everything else is channel-local and becomes `/drivers/<NAME>n`.
    """
    b = 300 + 20 * n
    bx, by = BLOCKS[n]

    def at(x: float, y: float):
        return (round(bx + x, 4), round(by + y, 4))

    U = f"U{b + 1}"
    L = f"L{b + 1}"
    D_CATCH, D_BOOT = f"D{b + 1}", f"D{b + 2}"
    Q = f"Q{b + 1}"
    R_SENSE, R_GATE, R_GPD = f"R{b + 1}", f"R{b + 2}", f"R{b + 3}"
    R_SNUB, R_OFF1, R_OFF2 = f"R{b + 4}", f"R{b + 5}", f"R{b + 6}"
    C_VIN, C_VINHF, C_SNUB = f"C{b + 1}", f"C{b + 2}", f"C{b + 3}"
    C_COFF, C_BOOT, C_VCC = f"C{b + 4}", f"C{b + 5}", f"C{b + 6}"

    # channel-local net names (final netlist form: /drivers/<name>)
    SW, CSN, VCC = f"SW{n}", f"CSN{n}", f"VCC{n}"
    BOOT, COFF, SHG, SNUB = f"BOOT{n}", f"COFF{n}", f"SHG{n}", f"SNUB{n}"
    # hierarchical nets - NO leading slash here; the root's local label adds
    # it (lumina-carrier root.py: hier pin "CDB" -> final net "/CDB").
    LED_A, DRV_EN, SHUNT = f"LED{n}_A", f"DRV_EN{n}", f"SHUNT{n}"
    VCC_NET = f"/drivers/{VCC}"      # exact netlist name, for the metadata

    # =====================================================================
    # U - TPS92515HV.  Pin 9 (PWM) is deliberately absent from `pins`: it
    # carries the hierarchical label instead, added below.
    # =====================================================================
    # Pin 6 (DRN) and pin 7 (CSN) share one node by datasheet instruction.
    # Pin 11 (exposed PowerPAD) is GND - "Thermal pad - Connect to ground",
    # and constraints.json thermal[] already demands >= 9 vias on it, so it
    # must stay a real netlist member (RthetaJC(bot) 5.3 vs RthetaJA 56.2
    # C/W: the pad is the dominant heat path, and sec 8.3.8 warns an
    # unsoldered pad reaches thermal shutdown prematurely).
    # Pin 10 (IADJ) shares the VCC node - Figure 17's bare-wire tie.
    sh.place_ic_with_decoupling(
        U, SYM_U, V_U, at=at(*IC_AT),
        pins={"1": COFF,      # COFF timing node (C304 + ROFF1 + ROFF2)
              "2": VCC,       # 5 V LDO OUTPUT - power_out, never flagged
              "3": "GND",
              "4": BOOT,      # bootstrap: C305 to SW, D302 from VCC
              "5": SW,        # internal FET SOURCE -> L, catch diode, C305
              "6": CSN,       # DRN, shorted to CSN
              "7": CSN,       # sense negative, low side of RSENSE
              "8": "+12V",    # VIN == sense positive; CIN on THIS side
              "10": VCC,      # IADJ tied to VCC (internal 2.4 V clamp)
              "11": "GND"},   # exposed PowerPAD
        footprint=FP_U,
        expect={"1": "COFF", "2": "VCC", "3": "GND", "4": "BOOT", "5": "SW",
                "6": "DRN", "7": "CSN", "8": "VIN", "9": "PWM",
                "10": "IADJ", "11": "EP"},
        decoupling=[
            # CIN sizing, Equation 21: CIN-MIN = ILED x (1/fSW - tOFF) /
            # dVIN-PP. At 0.275 A, 668 kHz, tOFF 649 ns and the datasheet's
            # own hard limit dVIN-PP <= min(10 % of VIN, 2 V) = 1.2 V, that
            # is 195 nF. 4.7 uF is 24x it - the binding constraint is the
            # LOOP2 area, not the value (sec 11.1).
            {"cap": C_VIN, "pin": "8", "rail": "+12V", "value": V_4U7,
             "lib_id": SYM_C4U7, "footprint": C0805},
            {"cap": C_VINHF, "pin": "8", "rail": "+12V", "value": V_100N,
             "lib_id": SYM_C100N, "footprint": C0603},
            # NEW REFDES (see module docstring): the VCC decoupler the Pin
            # Functions table requires. rail_net spells the FINAL netlist
            # name - a sheet-local label becomes /<sheet>/<NAME>, and S4's
            # metadata contract wants the exact board name.
            {"cap": C_VCC, "pin": "2", "rail": VCC, "rail_net": VCC_NET,
             "value": V_4U7, "lib_id": SYM_C4U7, "footprint": C0805},
        ],
        caps_at=at(*CAPS_AT), caps_dx=CAPS_DX)

    # PWM (pin 9) = this channel's enable, from `control` (/EN_OK through a
    # 0 R link, or the DNP one-shot). 3.3 V CMOS against a 1.0 V typical
    # threshold and a 5.5 V ABS MAX. No capacitor, no RC: sec 8.3.11.2's
    # 0.1 uF applies to a static VIN-UVLO divider, and blocks.md B2 caps any
    # network on this path at tau <= 14 ns.
    sh.hier_pin(DRV_EN, shape="input", ref=U, pad="9")

    # =====================================================================
    # power path: RSENSE -> (DRN/CSN) -> SW -> L -> LEDn_A, catch diode
    # =====================================================================
    # RSENSE 0.75 R (NOT 0.68 - p4-wiring-notes s1). IL_peak =
    # (VIADJ/10)/RSENSE and ILED = IL_peak - dIL_pp/2 with dIL_pp = 90 mA:
    # min 224 mV -> 0.254 A, typ 240 mV -> 0.275 A, max 251 mV -> 0.290 A.
    # The WHOLE band stays under the 300 mA design point, so worst-case
    # +12V draw is 0.693 A = 92 % of the ICD s6.2 0.75 A sustained ceiling
    # with every PWM stuck at 100 % and no firmware alive. That compliance
    # -by-construction is what requirements.md s3.3 makes non-optional.
    # P6: Kelvin the CSN tap and keep this part hard against VIN/CSN
    # (sec 8.3.2) - it is the most sensitive loop on the channel.
    sh.add_component(SYM_R_SENSE, R_SENSE, V_RSENSE, at(COL_C, Y_RSENSE),
                     footprint=R0805)
    sh.wire_pins(R_SENSE, {"1": "+12V", "2": CSN})

    # Catch diode: pin 1 = C (cathode) on SW, pin 2 = A (anode) on GND.
    # 60 V / 1 A, selected on Vf because Vf dominates the idle loss (at 0 %
    # commanded duty the converter free-runs into the shunt FET, duty
    # collapses to ~0.5 % and the diode conducts almost the whole cycle).
    sh.add_component(SYM_D_CATCH, D_CATCH, V_D_CATCH, at(COL_C, Y_DCATCH),
                     footprint=FP_D_CATCH, expect={"1": "C", "2": "A"})
    sh.wire_pins(D_CATCH, {"1": SW, "2": "GND"})

    # 47 uH, sized for RIPPLE not slew (blocks.md B3 rule 2): under shunt
    # dimming the converter never has to slew the LED current, the FET does.
    sh.add_component(SYM_L, L, V_L, at(COL_C, Y_L), footprint=FP_L)
    sh.wire_pins(L, {"1": SW, "2": LED_A})

    # ### NO OUTPUT CAPACITOR ACROSS THE LED STRING. ######################
    # There is deliberately NOTHING from LEDn_A to GND here. blocks.md B3
    # rule 1: the shunt FET dumps it every PWM cycle - 1 uF at 6.8 V and
    # 9.766 kHz is 0.23 W per channel, ten times the whole logic budget -
    # and TPS92515HV sec 9.2.1.7 says none is required ("Because current is
    # being regulated and is continuous, no output capacitance is required
    # ... This regulation helps when designing a high-frequency PWM dimming
    # on the LED load"). Figures 15, 42 and 43 are all captured with none.
    # A REVIEWER OR FIX LOOP WILL WANT TO ADD ONE. DO NOT.
    # #####################################################################

    # =====================================================================
    # BOOT network - NEW REFDES, see the module docstring
    # =====================================================================
    # Pin Functions, pin 4: "Connect a ceramic capacitor between BOOT and SW
    # and a diode from VCC to BOOT to power the high-side FET drive
    # circuitry." Without both parts the high-side FET has no gate supply.
    # Diode ANODE (pin 2 "A") on VCC, CATHODE (pin 1 "K") on BOOT: each time
    # the catch diode pulls SW below ground the boot cap recharges from VCC
    # through it, in ~150 ns. BOOT-SW settles at 4.09 V worst case against a
    # 3.5 V max BOOT-UVLO falling threshold (docstring deviation 2 carries
    # the arithmetic). BOOT-SW abs max is 5.5 V, so the 50 V cap is rated
    # far beyond need; BOOT-GND abs max is 70.5 V.
    sh.add_component(SYM_D_BOOT, D_BOOT, V_D_BOOT, at(COL_A, Y_DBOOT),
                     footprint=FP_D_BOOT, expect={"1": "K", "2": "A"})
    sh.wire_pins(D_BOOT, {"1": BOOT, "2": VCC})
    sh.add_component(SYM_C100N, C_BOOT, V_100N, at(COL_A, Y_CBOOT),
                     footprint=C0603)
    sh.wire_pins(C_BOOT, {"1": BOOT, "2": SW})

    # =====================================================================
    # COFF network (sec 8.3.4 / Figure 14) - THE SHUNT-DIMMING COMPENSATION
    # =====================================================================
    # C304 = COFF, 470 pF, the datasheet's own preferred value ("Select a
    # COFF between 100 pF and 1 nF. The preferred value is 470 pF").
    # C0G/NP0 IS MANDATORY, NOT A PREFERENCE - this is a timing capacitor
    # and X7R's voltage coefficient would drift the off-time, the ripple and
    # therefore the dimming linearity. P6: sec 11.1 wants it "close to the
    # COFF and GND pins to maximize noise rejection".
    c_coff = sh.add_component(SYM_C470P, C_COFF, V_470P, at(COL_A, Y_COFF),
                              footprint=C0603)
    sh.wire_pins(C_COFF, {"1": COFF, "2": "GND"})
    c_coff.set_property("Note", "COFF timer cap - C0G mandatory, at pin 1")

    # ROFF1 from VLED. On this board VLED IS the LEDn_A anode net that runs
    # out to J5 - not a local node. tOFF = dIL x L / VLED = 622 ns at 90 mA
    # / 47 uH / 6.8 V; eq 7 gives ROFF = 8.32 k -> E24 8.2 k, but ROFF2 sits
    # permanently in parallel and also charges COFF from 5 V, which would
    # shorten tOFF to 545 ns (-12 % ripple). Re-solving the Thevenin onto
    # the 90 mA design point gives 9.53 k (zero LCSC stock), so 10 k:
    # 649 ns, 93.9 mA, +4 %, 668 kHz. Reverting to TI's literal 8.2 k is a
    # one-line change if disputed.
    r_off1 = sh.add_component(SYM_R10K, R_OFF1, V_10K, at(COL_A, Y_ROFF1),
                              footprint=R0603)
    sh.wire_pins(R_OFF1, {"1": LED_A, "2": COFF})
    r_off1.set_property("Note", "ROFF1 from VLED (LED anode) - sec 8.3.4")

    # ROFF2 from THE DEVICE'S OWN VCC PIN 2. Eq 8/9 with VSHUNT = the shunt
    # FET's RDS(on) drop at 0.320 A (0.122 V typ / 0.186 V max) give 49.1 k
    # / 45.5 k, so E24 47 k sits between them; it is exactly right at
    # RDS(on) = 494 mOhm, mid-band for the Toshiba's 380-580 mOhm. Load is
    # 5.0 V / 47 k = 106 uA per DEVICE against the 500 uA external-load
    # allowance - each channel has its own VCC pin, so it is never 424 uA
    # on one regulator.
    # DO NOT re-source this from +3V3 or any external rail: the internal
    # COFF-to-VCC diode can then pull VCC up and start the device with VIN
    # unpowered (sec 8.3.4).
    r_off2 = sh.add_component(SYM_R47K, R_OFF2, V_47K, at(COL_A, Y_ROFF2),
                              footprint=R0603)
    sh.wire_pins(R_OFF2, {"1": VCC, "2": COFF})
    r_off2.set_property("Note", "ROFF2 from OWN VCC pin 2 - never +3V3")

    # =====================================================================
    # DNP SW-node RC snubber footprint (sheets.md s1.3)
    # =====================================================================
    # Series 1 nF + 10 R from SW to GND, fitted only if bring-up shows SW
    # ringing. Both parts are in the netlist so their pads, clearance and
    # area are accounted for at P6/P7 and the option stays a populate change
    # rather than a respin (sheets.md s4 note 1). 100 V cap so the same
    # footprint would serve the historical branch B unchanged.
    sh.add_component(SYM_C1N, C_SNUB, V_1N, at(COL_A, Y_CSNUB),
                     footprint=C0603)
    sh.wire_pins(C_SNUB, {"1": SW, "2": SNUB})
    sh.add_component(SYM_R10R, R_SNUB, V_10R, at(COL_A, Y_RSNUB),
                     footprint=R0603)
    sh.wire_pins(R_SNUB, {"1": SNUB, "2": "GND"})

    # =====================================================================
    # shunt FET - the part that actually delivers PAR-REQ-01's 141 ns
    # =====================================================================
    # SSM3K2615R (SOT-23F, NOT plain SOT-23): pin 1 = G, pin 2 = S,
    # pin 3 = D. Drain on the LED ANODE, source on GND, so the string is
    # shorted end to end and the gate drive stays ground-referenced at
    # 3.3 V - which is why RDS(on) specified AT VGS = 3.3 V (380 mOhm typ /
    # 580 mOhm max) is the spec that mattered when this part was chosen.
    # The package has NO polarity dot: orientation is defined by the lead
    # count per edge only, and a 180-degree error swaps GATE and SOURCE
    # while DRAIN stays put. That is a P6/P9 check (fp overlay + dfm_check),
    # flagged here because the schematic cannot catch it.
    sh.add_component(SYM_Q, Q, V_Q, at(COL_C, Y_Q), footprint=FP_Q,
                     expect={"1": "G", "2": "S", "3": "D"})
    sh.wire_pins(Q, {"1": SHG, "2": "GND", "3": LED_A})

    # 150 R gate series: bounds the 74LVC00A output to 22 mA and gives
    # ~30 ns edges into Ciss 150 pF (tau ~ 22 ns). DO NOT raise this into an
    # RC filter - the 141 ns PAR-REQ-01 response budget is the entire reason
    # this architecture exists (parts.json R302 role).
    sh.add_component(SYM_R150, R_GATE, V_150R, at(COL_C, Y_RGATE),
                     footprint=R0603)
    sh.hier_pin(SHUNT, shape="input", ref=R_GATE, pad="1")
    sh.wire_pin(R_GATE, "2", SHG)

    # 100 k gate pull-down: an unpowered or high-Z 74LVC00A must not leave
    # the shunt FET half-on. Vth is only 0.8 V min, so this is a fail-safe,
    # not a nicety.
    sh.add_component(SYM_R100K, R_GPD, V_100K, at(COL_C, Y_RGPD),
                     footprint=R0603)
    sh.wire_pins(R_GPD, {"1": SHG, "2": "GND"})

    # =====================================================================
    # rails and sheet interface
    # =====================================================================
    # +12V and GND are GLOBAL bare nets (sheets.md s2), so they are power
    # symbols, not sheet pins. flag=False on BOTH: the `power` sheet owns
    # the rail entry and therefore the PWR_FLAGs, and a second PWR_FLAG on
    # the same net would raise a power_out <-> power_out ERC conflict.
    # These symbols are what stop the sheet-local "GND"/"+12V" labels
    # becoming /drivers/GND and /drivers/+12V.
    sh.power_flag("GND", at=at(*RAIL_GND_AT), sym="power:GND", flag=False)
    sh.power_flag("+12V", at=at(*RAIL_12V_AT), sym="power:+12V", flag=False)

    # LEDn_A has three pins on this sheet (L pin 2, ROFF1 pin 1, Q drain),
    # so it uses the FREE-CLUSTER hier_pin variant: a local label of the net
    # name at one end and the hierarchical label at the other, joined by
    # wire geometry. schlib does not rely on hier-label/local-label name
    # merging, and neither does this sheet.
    sh.hier_pin(LED_A, shape="output", at=at(*HIER_LED_AT))

    # ------------------------------------------------------------ identity
    for ref, role in ((U, "U"), (L, "L"), (D_CATCH, "D_CATCH"),
                      (D_BOOT, "D_BOOT"), (Q, "Q"),
                      (R_SENSE, "R_SENSE"), (R_GATE, "R_GATE"),
                      (R_GPD, "R_GPD"), (R_SNUB, "R_SNUB"),
                      (R_OFF1, "R_OFF1"), (R_OFF2, "R_OFF2"),
                      (C_VIN, "C_VIN"), (C_VINHF, "C_VINHF"),
                      (C_SNUB, "C_SNUB"), (C_COFF, "C_COFF"),
                      (C_BOOT, "C_BOOT"), (C_VCC, "C_VCC")):
        sh.sch.components.get(ref).set_property("LCSC", LCSC[role])

    # DNP option set (sheets.md s4 note 1): marked in the BOM variant field
    # so P9 can exclude them. NOTE for the orchestrator: kicad-sch-api 0.5.6
    # models in_bom/on_board but has NO `dnp` attribute, so the KiCad symbol
    # DNP flag cannot be written from here - this field plus parts.json's
    # per-ref `dnp: true` are the machine-readable record.
    for ref in (C_SNUB, R_SNUB):
        sh.sch.components.get(ref).set_property("Variant", "DNP")


def build() -> schlib.Sheet:
    sh = schlib.Sheet(
        "drivers",
        title="LUM-PAR-A: drivers (4x TPS92515HV CC buck + shunt FET)",
        paper="A2", date="2026-08-07", company="ai-ee", pwr_base=300)
    for n in range(4):
        _channel(sh, n)
    return sh


def main(argv=None) -> int:
    # Default out dir is kicad/, and project=False: the ROOT generator owns
    # <root>.kicad_pro, this sheet must never write one.
    out_dir = Path(argv[0]) if argv else BOARD / "kicad"
    try:
        sh = build()
        path = sh.save(out_dir, project=False)
    except Exception as exc:  # noqa: BLE001  (SPEC 6: any error -> exit 2)
        print(json.dumps({"script": "gen.drivers", "status": "error",
                          "error": f"{type(exc).__name__}: {exc}"}))
        return 2
    print(json.dumps({
        "script": "gen.drivers", "status": "pass",
        "sheet": str(path),
        "components": len(list(sh.sch.components)),
        "hier_pins": sorted(sh.hier_pins),
        "decoupling_associations": len(sh.decoupling),
        "place_report": sh.place_report,
    }, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
