# of the 1.27 mm grid. Column A (x 25.4) holds the small-signal / timing
# parts that face the IC's left pins (COFF, VCC, GND, BOOT, SW); column C
# (x 127.0) holds the power path that faces the right pins (DRN, CSN, VIN).
# Slot pitch is 25.4 mm horizontally and 12.7 mm vertically: the longest
# stub reach on this sheet is the IC's 15.24 mm and the shunt FET's gate at
# 10.16 mm, so no label anchor can ever land on a neighbour's wire run
# (LEARNINGS 2026-07-22 [erc]: a label on a foreign wire silently merges
