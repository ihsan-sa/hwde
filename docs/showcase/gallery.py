#!/usr/bin/env python3
"""Generate the showcase's board gallery from the boards repo.

    gallery.py [--boards-root DIR] [--pictures] [--check]

Reads gallery.yaml (the curated order, words and extra pictures), the boards
repo's register.yaml, and each board's own .kicad_pcb and state.json, and
writes two copies of the same gallery:

  gallery.tex      \\input by hwde-showcase.tex: "The boards" chapter
  ../../README.md  the part between the gallery:start and gallery:end markers

A board the register lists and gallery.yaml does not is still shown, in a
"New boards" section, with a blurb from its requirements.md ("## 1. Function")
or, when it has none, its register title. A board that never reached a routed
layout (phase below P7 and no fab package) is named in one line, not pictured.

--pictures first makes the picture of any shown board that has none in
renders/: from the board's own render in its workspace when it has one,
finished by _finish.py, else by render_boards.sh. --check writes nothing and
exits 1 when either copy would change.

JSON to stdout; exit 0 done (or up to date with --check), 1 out of date
(--check) or a board that should be pictured has no picture, 2 error.
"""
